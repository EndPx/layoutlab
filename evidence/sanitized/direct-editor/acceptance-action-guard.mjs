import {chromium,expect} from '@playwright/test';
import {writeFileSync} from 'node:fs';

const browser=await chromium.launch({channel:'msedge',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
await page.goto('http://127.0.0.1:5182');
await page.getByText('Manual layout controls',{exact:true}).click();
const ed=page.getByTestId('layout-editor');
await ed.getByRole('button',{name:'Run baseline',exact:true}).click();
await page.getByTestId('layout-baseline').waitFor({timeout:90000});
await ed.getByRole('button',{name:'Edit layout',exact:true}).click();
await ed.getByRole('combobox',{name:'Rack',exact:true}).selectOption('R1');
const x=ed.getByRole('spinbutton',{name:'X centre (mm)'});
await x.fill('4100');
await x.press('Tab');
await expect(ed.getByRole('button',{name:/Rotate \+90/})).toBeDisabled();
await expect(page.getByRole('button',{name:'Rotate selected rack +90 degrees',exact:true})).toBeDisabled();
await expect(ed).toContainText('Translation pending. Apply or Undo before rotating this rack.');
await expect(x).toHaveValue('4100');
await ed.getByRole('button',{name:'Undo last edit',exact:true}).click();
await expect(x).toHaveValue('4000');
await ed.getByRole('button',{name:/Rotate \+90/}).click();
await expect(x).toBeDisabled();
await expect(ed.getByRole('button',{name:'Translate rack',exact:true})).toBeDisabled();
await expect(ed).toContainText('Rotation pending. Apply or Undo before moving this rack.');
await expect(ed.getByRole('button',{name:/Rotate \+90/})).toHaveAttribute('aria-pressed','true');
await page.screenshot({path:'evidence/sanitized/direct-editor/action-guard-rotation.png',fullPage:true});
await ed.getByRole('button',{name:'Undo last edit',exact:true}).click();
await expect(x).toBeEnabled();
await expect(ed.getByRole('button',{name:'Translate rack',exact:true})).toHaveAttribute('aria-pressed','true');
writeFileSync('evidence/sanitized/direct-editor/action-guard-check.json',JSON.stringify({browser:'installed msedge headless',translationPreserved:true,rotationPreserved:true,undoUnlocksBoth:true,sceneHandle:false,rotationControl:'viewport and keyboard-accessible buttons'}));
await browser.close();
